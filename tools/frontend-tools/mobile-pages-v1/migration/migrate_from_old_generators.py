class OldGeneratorPattern:
    """Represents patterns from old generators that need migration."""
    
    def __init__(self, pattern_type: str, file_pattern: str, content_patterns: List[str]):
        self.pattern_type = pattern_type  # 'dynamic', 'static', 'wrapper'
        self.file_pattern = file_pattern
        self.content_patterns = content_patterns


class MigrationDetector:
    """Detects old generator patterns in project files."""
    
    def __init__(self, frontend_root: Path):
        self.frontend_root = frontend_root
        self.src_dir = frontend_root / "src"
        
        # Define patterns from old generators
        self.old_patterns = [
            # Dynamic page generator patterns
            OldGeneratorPattern(
                "dynamic",
                "**/*Page.tsx",
                [
                    r"// Generated by.*dynamic.*generator",
                    r"// This file was auto-generated",
                    r"DynamicPageWrapper",
                    r"export.*DynamicPage"
                ]
            ),
            
            # Old page generator patterns
            OldGeneratorPattern(
                "static", 
                "**/*Page.tsx",
                [
                    r"// Generated by.*page.*generator",
                    r"StaticPageWrapper",
                    r"// Auto-generated page component"
                ]
            ),
            
            # Old wrapper patterns (parent wrappers that should be removed)
            OldGeneratorPattern(
                "wrapper",
                "**/components/**/*Wrapper.tsx",
                [
                    r"// Parent wrapper component",
                    r"// Generated wrapper",
                    r"MobileWrapper.*Parent"
                ]
            )
        ]
    
    def detect_old_generator_files(self) -> Dict[str, List[Path]]:
        """Detect files generated by old generators."""
        detected_files = {
            "dynamic": [],
            "static": [], 
            "wrapper": [],
            "unknown": []
        }
        
        print("🔍 Scanning for old generator patterns...")
        
        if not self.src_dir.exists():
            print(f"  ⚠️  Source directory not found: {self.src_dir}")
            return detected_files
        
        # Scan all relevant files
        for pattern in self.old_patterns:
            for file_path in self.src_dir.glob(pattern.file_pattern):
                if file_path.is_file():
                    try:
                        content = file_path.read_text(encoding='utf-8')
                        
                        # Check if file matches any old generator pattern
                        for content_pattern in pattern.content_patterns:
                            if re.search(content_pattern, content, re.IGNORECASE):
                                detected_files[pattern.pattern_type].append(file_path)
                                print(f"  📄 Found {pattern.pattern_type}: {file_path.relative_to(self.frontend_root)}")
                                break
                                
                    except Exception as e:
                        print(f"  ⚠️  Error reading {file_path}: {e}")
        
        # Report totals
        total_found = sum(len(files) for files in detected_files.values())
        print(f"  📊 Total old generator files found: {total_found}")
        
        return detected_files
    
    def analyze_migration_complexity(self, detected_files: Dict[str, List[Path]]) -> Dict[str, any]:
        """Analyze the complexity of migration required."""
        analysis = {
            "total_files": sum(len(files) for files in detected_files.values()),
            "by_type": {},
            "parent_pages": set(),
            "child_pages": set(),
            "wrapper_cleanup": [],
            "complexity_score": 0
        }
        
        print("🔬 Analyzing migration complexity...")
        
        for pattern_type, files in detected_files.items():
            analysis["by_type"][pattern_type] = len(files)
            
            for file_path in files:
                rel_path = file_path.relative_to(self.src_dir)
                
                # Determine if it's a parent or child page
                if "pages" in rel_path.parts:
                    page_parts = list(rel_path.parts)
                    if "pages" in page_parts:
                        pages_index = page_parts.index("pages")
                        if len(page_parts) > pages_index + 1:
                            parent_name = page_parts[pages_index + 1]
                            
                            # If it's the main parent page (e.g., SettingsPage.tsx in settings/)
                            if file_path.stem == f"{parent_name.capitalize()}Page":
                                analysis["parent_pages"].add(parent_name)
                            else:
                                # It's likely a child page
                                analysis["child_pages"].add((parent_name, file_path.stem))
                
                # Check for parent wrappers that need removal
                if pattern_type == "wrapper" and "components" in rel_path.parts:
                    analysis["wrapper_cleanup"].append(file_path)
        
        # Calculate complexity score
        analysis["complexity_score"] = (
            len(analysis["parent_pages"]) * 2 +  # Parent pages are more complex
            len(analysis["child_pages"]) * 1 +   # Child pages are simpler
            len(analysis["wrapper_cleanup"]) * 3  # Wrapper cleanup is complex
        )
        
        print(f"  📊 Migration Analysis:")
        print(f"    Parents to migrate: {len(analysis['parent_pages'])}")
        print(f"    Children to migrate: {len(analysis['child_pages'])}")
        print(f"    Wrappers to cleanup: {len(analysis['wrapper_cleanup'])}")
        print(f"    Complexity Score: {analysis['complexity_score']}")
        
        return analysis


class ProjectMigrator:
    """Handles migration from old generators to new template-based system."""
    
    def __init__(self, frontend_root: Path, templates_dir: Path, dry_run: bool = True):
        self.frontend_root = frontend_root
        self.templates_dir = templates_dir
        self.dry_run = dry_run
        
        # Initialize components
        self.detector = MigrationDetector(frontend_root)
        self.project_detector = ProjectCapabilityDetector(frontend_root)
        self.template_engine = TemplateEngine(templates_dir)
        self.file_writer = FileWriter()
        self.variable_generator = VariableGenerator()
        self.validator = ProjectValidator(frontend_root, templates_dir)
    
    def run_migration(self) -> Dict[str, any]:
        """Run complete migration process."""
        print("🚀 Starting Migration Process")
        print("=" * 60)
        
        migration_report = {
            "detected_files": {},
            "analysis": {},
            "migration_plan": {},
            "execution_results": {},
            "validation_results": {}
        }
        
        # Step 1: Detect old generator files
        migration_report["detected_files"] = self.detector.detect_old_generator_files()
        
        if not any(migration_report["detected_files"].values()):
            print("✅ No old generator files detected. Migration not needed.")
            return migration_report
        
        # Step 2: Analyze migration complexity
        migration_report["analysis"] = self.detector.analyze_migration_complexity(
            migration_report["detected_files"]
        )
        
        # Step 3: Create migration plan
        migration_report["migration_plan"] = self._create_migration_plan(
            migration_report["analysis"]
        )
        
        # Step 4: Execute migration (if not dry run)
        if not self.dry_run:
            migration_report["execution_results"] = self._execute_migration(
                migration_report["migration_plan"]
            )
        else:
            print("🔍 DRY RUN MODE - No changes will be made")
            self._preview_migration(migration_report["migration_plan"])
        
        # Step 5: Validate results
        migration_report["validation_results"] = self._validate_migration()
        
        return migration_report
    
    def _create_migration_plan(self, analysis: Dict[str, any]) -> Dict[str, any]:
        """Create detailed migration plan."""
        print("\n📋 Creating Migration Plan...")
        
        plan = {
            "backup_originals": [],
            "remove_parent_wrappers": [],
            "convert_to_templates": [],
            "update_routing": [],
            "regenerate_dependencies": False
        }
        
        # Plan to backup all files being modified
        all_files = []
        for files in self.detector.detect_old_generator_files().values():
            all_files.extend(files)
        plan["backup_originals"] = all_files
        
        # Plan parent wrapper removal
        plan["remove_parent_wrappers"] = analysis["wrapper_cleanup"]
        
        # Plan template conversion for each page
        for parent in analysis["parent_pages"]:
            plan["convert_to_templates"].append({
                "type": "parent",
                "name": parent,
                "action": "convert_to_template_based"
            })
        
        for parent, child in analysis["child_pages"]:
            plan["convert_to_templates"].append({
                "type": "child",
                "name": child.replace("Page", ""),
                "parent": parent,
                "action": "convert_to_template_based"
            })
        
        # Plan routing updates
        plan["update_routing"] = list(analysis["parent_pages"])
        
        # Plan dependency regeneration if needed
        plan["regenerate_dependencies"] = len(analysis["parent_pages"]) > 0
        
        print(f"  📝 Migration Plan Created:")
        print(f"    Files to backup: {len(plan['backup_originals'])}")
        print(f"    Parent wrappers to remove: {len(plan['remove_parent_wrappers'])}")
        print(f"    Pages to convert: {len(plan['convert_to_templates'])}")
        print(f"    Routing updates needed: {len(plan['update_routing'])}")
        
        return plan
    
    def _preview_migration(self, plan: Dict[str, any]):
        """Preview what migration would do without making changes."""
        print("\n🔍 Migration Preview (Dry Run):")
        print("=" * 40)
        
        print("\n1. Backup Original Files:")
