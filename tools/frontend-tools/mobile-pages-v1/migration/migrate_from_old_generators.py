def main():
    """Main CLI interface for migration tool."""
    parser = argparse.ArgumentParser(
        description="Migrate projects from old generators to template-based system",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s /path/to/frontend --dry-run
  %(prog)s /path/to/frontend --execute
  %(prog)s . --analyze-only
        """
    )
    
    parser.add_argument(
        'frontend_root',
        help='Path to frontend root directory'
    )
    
    parser.add_argument(
        '--dry-run',
        action='store_true',
        default=True,
        help='Preview migration without making changes (default)'
    )
    
    parser.add_argument(
        '--execute',
        action='store_true',
        help='Actually execute the migration'
    )
    
    parser.add_argument(
        '--analyze-only',
        action='store_true',
        help='Only analyze and detect old patterns, do not create migration plan'
    )
    
    parser.add_argument(
        '--templates-dir',
        help='Path to templates directory (defaults to ./templates)'
    )
    
    args = parser.parse_args()
    
    # Determine dry run mode
    dry_run = not args.execute
    
    # Setup paths
    frontend_root = Path(args.frontend_root).resolve()
    if not frontend_root.exists():
        print(f"❌ Frontend root directory not found: {frontend_root}")
        sys.exit(1)
    
    templates_dir = Path(args.templates_dir) if args.templates_dir else Path(__file__).parent.parent / "templates"
    if not templates_dir.exists():
        print(f"❌ Templates directory not found: {templates_dir}")
        sys.exit(1)
    
    try:
        # Initialize migrator
        migrator = ProjectMigrator(frontend_root, templates_dir, dry_run)
        
        if args.analyze_only:
            # Just analyze and detect
            detected_files = migrator.detector.detect_old_generator_files()
            analysis = migrator.detector.analyze_migration_complexity(detected_files)
            
            print("\n📊 Analysis Complete:")
            if analysis["total_files"] == 0:
                print("✅ No migration needed - no old generator files detected")
            else:
                print(f"⚠️  {analysis['total_files']} files need migration")
                print(f"   Complexity Score: {analysis['complexity_score']}")
        else:
            # Run full migration
            migration_report = migrator.run_migration()
            
            # Print final summary
            print("\n" + "=" * 60)
            print("🏁 MIGRATION COMPLETE")
            print("=" * 60)
            
            total_files = sum(len(files) for files in migration_report["detected_files"].values())
            if total_files == 0:
                print("✅ No migration was needed")
            else:
                print(f"📊 Migration Summary:")
                print(f"   Files Processed: {total_files}")
                
                if "execution_results" in migration_report and migration_report["execution_results"]:
                    results = migration_report["execution_results"]
                    print(f"   Pages Converted: {len(results.get('pages_converted', []))}")
                    print(f"   Errors: {len(results.get('errors', []))}")
                    
                    if results.get('errors'):
                        print(f"\n⚠️  Errors occurred:")
                        for error in results['errors']:
                            print(f"   - {error}")
                
                if migration_report.get("validation_results"):
                    validation = migration_report["validation_results"]
                    status = "✅ PASSED" if validation["overall_passed"] else "❌ FAILED"
                    print(f"   Validation: {status}")
    
    except KeyboardInterrupt:
        print("\n\n⚠️  Migration cancelled by user")
        sys.exit(1)
    except Exception as e:
        print(f"\n❌ Migration failed: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()