import { Router } from 'express';
import { authenticate } from '../middleware/auth';
import { validate } from '../middleware/validation';
import { ProfileService } from '../services/profileService';
import { CreateProfileRequest, UpdateProfileRequest } from '../models/Profile';

const router = Router();
const profileService = new ProfileService();


// GET /:userId
router.get('/:userId', authenticate, async (req: any, res) => {
  try {
    const result = await profileService.getProfile();
    res.json({ success: true, data: result });
  } catch (error: any) {
    res.status(400).json({ success: false, error: error.message });
  }
});

// PUT /:userId
router.put('/:userId', authenticate, async (req: any, res) => {
  try {
    const result = await profileService.updateProfile(req.userId, req.body);
    res.json({ success: true, data: result });
  } catch (error: any) {
    res.status(400).json({ success: false, error: error.message });
  }
});

